// Builds a complete, runnable DESeq2 analysis script from a configuration object.
// Plain JavaScript so the same code runs in the browser (script generator page) and
// in Node (scripts/test-script.mjs, which runs the generated script in R on the airway data).

/** @typedef {{
 *  input: "salmon" | "counts",
 *  quantDir: string, countsFile: string, samplesFile: string, gtfFile: string, outDir: string,
 *  sampleCol: string, conditionCol: string, refLevel: string, trtLevel: string, batchCol: string,
 *  organism: "human" | "mouse",
 *  minCounts: number, minSamples: number, alpha: number, lfc: number,
 *  shrink: "apeglm" | "ashr" | "none",
 *  plots: { pca: boolean, ma: boolean, volcano: boolean, heatmap: boolean, counts: boolean, phist: boolean },
 *  heatmapN: number, countGenes: string[], enrichment: boolean, labelTop: number
 * }} Config */

/** @type {Config} */
export const defaults = {
  input: "salmon", quantDir: "quant", countsFile: "counts.csv", samplesFile: "samples.csv", gtfFile: "ref/annotation.gtf.gz", outDir: "results",
  sampleCol: "sample", conditionCol: "condition", refLevel: "control", trtLevel: "treated", batchCol: "",
  organism: "human", minCounts: 10, minSamples: 3, alpha: 0.05, lfc: 1, shrink: "apeglm",
  plots: { pca: true, ma: true, volcano: true, heatmap: true, counts: false, phist: true }, heatmapN: 30, countGenes: [], enrichment: true, labelTop: 10,
};

const rstr = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const rsym = (s) => (/^[A-Za-z.][A-Za-z0-9._]*$/.test(s) ? s : `\`${s.replace(/`/g, "")}\``);

/** @param {Config} c */
export function buildScript(c) {
  const orgdb = c.organism === "mouse" ? "org.Mm.eg.db" : "org.Hs.eg.db";
  const cond = rsym(c.conditionCol), batch = c.batchCol ? rsym(c.batchCol) : "";
  const design = batch ? `~ ${batch} + ${cond}` : `~ ${cond}`;
  const coefName = `${c.conditionCol}_${c.trtLevel}_vs_${c.refLevel}`;
  const pk = ["DESeq2", "tximport", "rtracklayer", orgdb, "ggplot2", "pheatmap"];
  if (c.shrink === "apeglm") pk.push("apeglm"); if (c.shrink === "ashr") pk.push("ashr");
  if (c.enrichment) pk.push("clusterProfiler");
  const L = [];
  const p = (...lines) => L.push(...lines);

  p(`# ============================================================================`,
    `# Differential expression with DESeq2`,
    `# Generated by Reads to Results (${new Date().toISOString().slice(0, 10)}). Read it before you run it:`,
    `# every setting below is a decision, and the comments say what each one does.`,
    `#`,
    `# Expected layout (relative to the folder you run this from):`,
    c.input === "salmon" ? `#   ${c.quantDir}/<sample>/quant.sf     one Salmon output folder per sample` : `#   ${c.countsFile}                      raw counts, genes in rows, samples in columns`,
    `#   ${c.samplesFile}                      sample sheet with columns ${c.sampleCol}, ${c.conditionCol}${c.batchCol ? ", " + c.batchCol : ""}`,
    c.input === "salmon" ? `#   ${c.gtfFile}        the GTF of the annotation you built the Salmon index from` : `#`,
    `#   ${c.outDir}/                        created; all outputs go here`,
    `# ============================================================================`,
    ``,
    `suppressPackageStartupMessages({`,
    ...pk.map((x, i) => `  library(${x})${i < pk.length - 1 ? "" : ""}`),
    `})`,
    `set.seed(1)`,
    `dir.create(${rstr(c.outDir)}, showWarnings = FALSE, recursive = TRUE)`,
    `out <- function(f) file.path(${rstr(c.outDir)}, f)`,
    ``,
    `# ---- 1. Sample sheet -------------------------------------------------------`,
    `samples <- read.csv(${rstr(c.samplesFile)}, stringsAsFactors = FALSE, check.names = FALSE)`,
    `needed <- c(${[c.sampleCol, c.conditionCol, c.batchCol].filter(Boolean).map(rstr).join(", ")})`,
    `missing_cols <- setdiff(needed, colnames(samples))`,
    `if (length(missing_cols)) stop("The sample sheet lacks these columns: ", paste(missing_cols, collapse = ", "),`,
    `                              "\\n  Columns found: ", paste(colnames(samples), collapse = ", "))`,
    `samples$${cond} <- factor(samples$${cond})`,
    `if (!all(c(${rstr(c.refLevel)}, ${rstr(c.trtLevel)}) %in% levels(samples$${cond})))`,
    `  stop("Condition levels found: ", paste(levels(samples$${cond}), collapse = ", "),`,
    `       "\\n  Expected ", ${rstr(c.refLevel)}, " (reference) and ", ${rstr(c.trtLevel)}, " (treatment). Fix the sheet or this script.")`,
    `samples$${cond} <- relevel(samples$${cond}, ref = ${rstr(c.refLevel)})   # reference level: fold changes are relative to it`,
    batch ? `samples$${batch} <- factor(samples$${batch})` : `# (no batch / pairing column)`,
    `rownames(samples) <- samples$${rsym(c.sampleCol)}`,
    `print(table(samples$${cond}${batch ? `, samples$${batch}` : ""}))`,
    ``);

  if (c.input === "salmon") {
    p(`# ---- 2. Transcript-to-gene table from the GTF ------------------------------`,
      `gtf <- rtracklayer::import(${rstr(c.gtfFile)})`,
      `tx <- gtf[gtf$type == "transcript"]`,
      `tx2gene <- unique(data.frame(TXNAME = tx$transcript_id, GENEID = tx$gene_id))`,
      ``,
      `# ---- 3. Import Salmon quantifications with tximport ------------------------`,
      `files <- file.path(${rstr(c.quantDir)}, samples$${rsym(c.sampleCol)}, "quant.sf")`,
      `names(files) <- samples$${rsym(c.sampleCol)}`,
      `if (!all(file.exists(files))) stop("quant.sf not found for: ", paste(names(files)[!file.exists(files)], collapse = ", "))`,
      `txi <- tximport(files, type = "salmon", tx2gene = tx2gene, ignoreTxVersion = TRUE)`,
      `cat("Imported", nrow(txi$counts), "genes for", ncol(txi$counts), "samples\\n")`,
      ``,
      `# ---- 4. DESeqDataSet -------------------------------------------------------`,
      `# The average transcript length per gene and sample is passed as an offset.`,
      `dds <- DESeqDataSetFromTximport(txi, colData = samples, design = ${design})`,
      ``);
  } else {
    p(`# ---- 2. Count matrix -------------------------------------------------------`,
      `# Raw integer counts (not TPM, not FPKM, not normalized). First column = gene IDs.`,
      `counts <- as.matrix(read.csv(${rstr(c.countsFile)}, row.names = 1, check.names = FALSE))`,
      `if (any(counts %% 1 != 0, na.rm = TRUE)) stop("The count matrix has non-integer values; DESeq2 needs raw counts.")`,
      `missing_s <- setdiff(samples$${rsym(c.sampleCol)}, colnames(counts))`,
      `if (length(missing_s)) stop("Samples in the sheet but not in the count matrix: ", paste(missing_s, collapse = ", "),`,
      `                           "\\n  Matrix columns: ", paste(colnames(counts), collapse = ", "))`,
      `counts <- counts[, samples$${rsym(c.sampleCol)}]     # same order as the sample sheet`,
      `stopifnot(identical(colnames(counts), rownames(samples)))`,
      `cat("Loaded", nrow(counts), "genes for", ncol(counts), "samples\\n")`,
      ``,
      `# ---- 3. DESeqDataSet -------------------------------------------------------`,
      `dds <- DESeqDataSetFromMatrix(countData = counts, colData = samples, design = ${design})`,
      ``);
  }

  p(`# ---- Filter genes with almost no counts ------------------------------------`,
    `# Keep genes with at least ${c.minCounts} counts in at least ${c.minSamples} samples (the size of the smallest group).`,
    `keep <- rowSums(counts(dds) >= ${c.minCounts}) >= ${c.minSamples}`,
    `cat("Genes before filter:", nrow(dds), " after:", sum(keep), "\\n")`,
    `dds <- dds[keep, ]`,
    ``,
    `# ---- Run DESeq2 ------------------------------------------------------------`,
    `dds <- DESeq(dds)`,
    `saveRDS(dds, out("dds.rds"))`,
    ``,
    `# ---- Results: ${c.trtLevel} versus ${c.refLevel} -------------------------------`,
    `res <- results(dds, contrast = c(${rstr(c.conditionCol)}, ${rstr(c.trtLevel)}, ${rstr(c.refLevel)}), alpha = ${c.alpha})`,
    `summary(res)`,
    `# Gene symbols from Ensembl IDs. If your IDs are not Ensembl, change "ENSEMBL" to the matching key type`,
    `# (e.g. "ENTREZID"); if they are already symbols, this step simply leaves the symbol column empty.`,
    `res$symbol <- tryCatch(AnnotationDbi::mapIds(${orgdb}, sub("\\\\..*$", "", rownames(res)), "SYMBOL", "ENSEMBL", multiVals = "first"),`,
    `                       error = function(e) { message("Symbols not added: the gene IDs are not Ensembl IDs of this organism."); NA_character_ })`);
  if (c.shrink !== "none") {
    p(``, `# Shrunken fold changes, for ranking and plots (the test itself is unchanged)`,
      c.shrink === "apeglm" ? `resLFC <- lfcShrink(dds, coef = ${rstr(coefName)}, type = "apeglm")` : `resLFC <- lfcShrink(dds, contrast = c(${rstr(c.conditionCol)}, ${rstr(c.trtLevel)}, ${rstr(c.refLevel)}), type = "ashr")`,
      `res$shrunk_log2FoldChange <- resLFC$log2FoldChange[match(rownames(res), rownames(resLFC))]`);
  }
  p(``,
    `res_df <- as.data.frame(res[order(res$padj, res$pvalue), ])`,
    `res_df <- cbind(gene_id = rownames(res_df), res_df)`,
    `write.csv(res_df, out("deseq2_results.csv"), row.names = FALSE)`,
    `sig <- res_df[!is.na(res_df$padj) & res_df$padj < ${c.alpha} & abs(res_df$log2FoldChange) > ${c.lfc}, ]`,
    `sig$direction <- ifelse(sig$log2FoldChange > 0, "up", "down")`,
    `write.csv(sig, out("significant_genes_padj${c.alpha}_lfc${c.lfc}.csv"), row.names = FALSE)`,
    `cat("Significant (padj < ${c.alpha}, |log2FC| > ${c.lfc}):", nrow(sig), " up:", sum(sig$direction == "up"), " down:", sum(sig$direction == "down"), "\\n")`,
    ``,
    `# ---- Transformed counts for PCA and heatmaps ------------------------------`,
    `vsd <- vst(dds, blind = FALSE)`,
    `write.csv(assay(vsd), out("vst_matrix.csv"))`,
    `write.csv(counts(dds, normalized = TRUE), out("normalized_counts.csv"))`,
    ``);

  const plots = [];
  if (c.plots.pca) plots.push(
    `# PCA: do the samples separate by ${c.conditionCol}? Is any sample alone?`,
    `pca <- plotPCA(vsd, intgroup = c(${[c.conditionCol, c.batchCol].filter(Boolean).map(rstr).join(", ")}), returnData = TRUE)`,
    `pv <- round(100 * attr(pca, "percentVar"))`,
    `g <- ggplot(pca, aes(PC1, PC2, color = ${cond}${batch ? `, shape = ${batch}` : ""})) + geom_point(size = 3.5) +`,
    `  xlab(paste0("PC1: ", pv[1], "% variance")) + ylab(paste0("PC2: ", pv[2], "% variance")) + coord_fixed() + theme_bw(base_size = 12)`,
    `ggsave(out("pca.pdf"), g, width = 5, height = 4); ggsave(out("pca.png"), g, width = 5, height = 4, dpi = 300)`,
    ``);
  if (c.plots.phist) plots.push(
    `# p-value histogram: flat with a spike near zero is healthy`,
    `png(out("pvalue_histogram.png"), width = 1200, height = 900, res = 200)`,
    `hist(res$pvalue[res$baseMean > 1], breaks = 20, col = "grey70", border = "white", main = "p-values", xlab = "p-value")`,
    `dev.off()`,
    ``);
  if (c.plots.ma) plots.push(
    `# MA plot`,
    `png(out("ma_plot.png"), width = 1400, height = 1100, res = 200)`,
    c.shrink !== "none" ? `plotMA(resLFC, ylim = c(-5, 5), alpha = ${c.alpha}, main = "MA plot (shrunken fold changes)")` : `plotMA(res, ylim = c(-5, 5), alpha = ${c.alpha})`,
    `dev.off()`,
    ``);
  if (c.plots.volcano) plots.push(
    `# Volcano plot (ggplot2; for journal-size SVG/PNG exports, use the Explore your results tool on deseq2_results.csv)`,
    `vdf <- res_df[!is.na(res_df$padj), ]`,
    `vdf$class <- ifelse(vdf$padj < ${c.alpha} & vdf$log2FoldChange > ${c.lfc}, "up", ifelse(vdf$padj < ${c.alpha} & vdf$log2FoldChange < -${c.lfc}, "down", "ns"))`,
    `lab <- head(vdf[vdf$class != "ns", ], ${c.labelTop})`,
    `g <- ggplot(vdf, aes(log2FoldChange, -log10(padj), color = class)) + geom_point(size = 0.8, alpha = 0.7) +`,
    `  scale_color_manual(values = c(up = "#D55E00", down = "#0072B2", ns = "grey75")) +`,
    `  geom_hline(yintercept = -log10(${c.alpha}), linetype = 2, color = "grey40") + geom_vline(xintercept = c(-${c.lfc}, ${c.lfc}), linetype = 2, color = "grey40") +`,
    `  geom_text(data = lab, aes(label = ifelse(is.na(symbol), gene_id, symbol)), size = 3, vjust = -0.6, show.legend = FALSE, fontface = "italic") +`,
    `  labs(x = "log2 fold change", y = "-log10 adjusted p", color = NULL) + theme_bw(base_size = 12) + theme(legend.position = "top")`,
    `ggsave(out("volcano.pdf"), g, width = 5.5, height = 5); ggsave(out("volcano.png"), g, width = 5.5, height = 5, dpi = 300)`,
    ``);
  if (c.plots.heatmap) plots.push(
    `# Heatmap of the ${c.heatmapN} most significant genes (row z-scores)`,
    `top_ids <- head(rownames(res)[order(res$padj)], ${c.heatmapN})`,
    `mat <- assay(vsd)[top_ids, ]`,
    `rownames(mat) <- ifelse(is.na(res[top_ids, "symbol"]), top_ids, res[top_ids, "symbol"])`,
    `ann <- as.data.frame(colData(vsd)[, c(${[c.conditionCol, c.batchCol].filter(Boolean).map(rstr).join(", ")}), drop = FALSE])`,
    `pheatmap(mat, scale = "row", annotation_col = ann, fontsize_row = 8, filename = out("heatmap_top${c.heatmapN}.png"), width = 7, height = 8)`,
    ``);
  if (c.plots.counts && c.countGenes.length) plots.push(
    `# Normalized counts of chosen genes, one panel each`,
    `genes_of_interest <- c(${c.countGenes.map(rstr).join(", ")})   # symbols or IDs`,
    `ids <- rownames(res)[match(genes_of_interest, res$symbol)]; ids[is.na(ids)] <- genes_of_interest[is.na(ids)]`,
    `ids <- ids[ids %in% rownames(dds)]`,
    `pdf(out("gene_counts.pdf"), width = 4, height = 4)`,
    `for (g in ids) plotCounts(dds, gene = g, intgroup = ${rstr(c.conditionCol)}, main = ifelse(is.na(res[g, "symbol"]), g, res[g, "symbol"]))`,
    `dev.off()`,
    ``);
  if (plots.length) p(`# ---- Plots ----------------------------------------------------------------`, ...plots);

  if (c.enrichment) p(
    `# ---- GO enrichment (biological process) -----------------------------------`,
    `# Over-representation of the significant genes against all tested genes as background.`,
    `sig_ids <- sub("\\\\..*$", "", rownames(res)[which(res$padj < ${c.alpha} & abs(res$log2FoldChange) > ${c.lfc})])`,
    `universe <- sub("\\\\..*$", "", rownames(res)[!is.na(res$padj)])`,
    `ego <- tryCatch(enrichGO(gene = sig_ids, universe = universe, OrgDb = ${orgdb}, keyType = "ENSEMBL", ont = "BP",`,
    `                         pAdjustMethod = "BH", qvalueCutoff = 0.05, readable = TRUE),`,
    `                error = function(e) { message("GO enrichment skipped: ", conditionMessage(e)); NULL })`,
    `ego_df <- if (is.null(ego)) data.frame() else as.data.frame(ego)`,
    `write.csv(ego_df, out("go_bp_enrichment.csv"), row.names = FALSE)`,
    `cat("Enriched GO BP terms:", nrow(ego_df), "\\n")`,
    `if (nrow(ego_df) > 0) { g <- dotplot(ego, showCategory = 15); ggsave(out("go_dotplot.png"), g, width = 8, height = 7, dpi = 300) }`,
    ``);

  p(`# ---- Record the software versions (paste into your methods) ---------------`,
    `writeLines(capture.output(sessionInfo()), out("sessionInfo.txt"))`,
    `cat("Done. Outputs are in ${c.outDir}/\\n")`,
    ``);
  return L.join("\n");
}

/** @param {Config} c */
export function buildNotebook(c) {
  const script = buildScript(c);
  const cells = [];
  const md = (s) => cells.push({ cell_type: "markdown", metadata: {}, source: [s] });
  const code = (s) => cells.push({ cell_type: "code", execution_count: null, metadata: {}, outputs: [], source: [s] });
  md("# DESeq2 analysis\n\nGenerated by Reads to Results. In Google Colab choose **Runtime → Change runtime type → R** first. The install cell takes about ten minutes.");
  const orgdb = c.organism === "mouse" ? "org.Mm.eg.db" : "org.Hs.eg.db";
  code(`if (!requireNamespace("BiocManager", quietly = TRUE)) install.packages("BiocManager")\nBiocManager::install(c("DESeq2", "tximport", "rtracklayer", "${orgdb}", "pheatmap"${c.shrink === "apeglm" ? ', "apeglm"' : c.shrink === "ashr" ? ', "ashr"' : ""}${c.enrichment ? ', "clusterProfiler"' : ""}), update = FALSE, ask = FALSE)`);
  md("Upload your files to the notebook's working folder (Files panel on the left) so that the paths in the script match, then run the next cell.");
  for (const block of script.split(/\n(?=# ---- )/)) code(block);
  return JSON.stringify({ cells, metadata: { kernelspec: { display_name: "R", language: "R", name: "ir" }, language_info: { name: "R" } }, nbformat: 4, nbformat_minor: 5 }, null, 1);
}
